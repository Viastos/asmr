export type ActiveCharacter = 'atomfurki' | 'utkumuney' | 'onplayer' | 'mirmanu';

export function getCharacterByClicks(clicks: number): { name: ActiveCharacter; label: string; range: string; cycleCount: number } {
  const cycleLength = 300;
  const cycleCount = Math.floor(clicks / cycleLength);
  const clickInCycle = clicks % cycleLength;
  const cycleSuffix = cycleCount > 0 ? ` #${cycleCount + 1}` : '';

  if (clickInCycle < 50) {
    return { name: 'atomfurki', label: `atomfurki${cycleSuffix}`, range: `${cycleCount * cycleLength} - ${cycleCount * cycleLength + 49}`, cycleCount };
  } else if (clickInCycle < 100) {
    return { name: 'utkumuney', label: `utkumuney${cycleSuffix}`, range: `${cycleCount * cycleLength + 50} - ${cycleCount * cycleLength + 99}`, cycleCount };
  } else if (clickInCycle < 150) {
    return { name: 'onplayer', label: `onplayer${cycleSuffix}`, range: `${cycleCount * cycleLength + 100} - ${cycleCount * cycleLength + 149}`, cycleCount };
  } else {
    return { name: 'mirmanu', label: `mirmanu${cycleSuffix}`, range: `${cycleCount * cycleLength + 150} - ${cycleCount * cycleLength + 299}`, cycleCount };
  }
}
